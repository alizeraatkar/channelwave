using ChannelWave.Core;
using ChannelWave.UI;
using ChannelWave.Telegram;
using ChannelWave.Platform.Browser;
using Bit.BlazorUI;
using Microsoft.AspNetCore.Components.Web;
using Microsoft.AspNetCore.Components.WebAssembly.Hosting;
var builder = WebAssemblyHostBuilder.CreateDefault(args);
builder.RootComponents.Add<Diagnostic>("#app");
builder.RootComponents.Add<HeadOutlet>("head::after");
builder.Services.AddScoped(sp => new HttpClient { BaseAddress = new Uri(builder.HostEnvironment.BaseAddress) });
builder.Services.AddBitBlazorUIServices();
builder.Services.AddSingleton<BrowserBridge>();
builder.Services.AddSingleton<ITdTransport, BrowserTdTransport>();
builder.Services.AddSingleton<TelegramSession>();
builder.Services.AddSingleton<HomeSessionState>();
builder.Services.AddScoped<HomeCollectionReader>();
builder.Services.AddSingleton<ILibraryRepository, BrowserLibrary>();
builder.Services.AddSingleton<SourceIndexer>();
builder.Services.AddSingleton<ChannelSync>();
builder.Services.AddSingleton<ChannelCatalog>();
builder.Services.AddSingleton<IAudioEngine, BrowserAudio>();
builder.Services.AddSingleton(sp => new PlaybackCoordinator(sp.GetRequiredService<IAudioEngine>(), sp.GetRequiredService<TelegramSession>().MediaWork, sp.GetRequiredService<ILibraryRepository>() as IListeningStore));
builder.Services.AddScoped<ListeningPlaybackActions>();
        builder.Services.AddScoped<ArtworkCoordinator>();
builder.Services.AddScoped<IMetadataSource, MetadataMediaSource>();
builder.Services.AddScoped<MetadataScanner>();
builder.Services.AddScoped<BrowserRuntime>();
builder.Services.AddScoped<IRuntimeHost, WebRuntimeHost>();
builder.Services.AddScoped<PlaybackMediaResolver>();
builder.Services.AddScoped<MediaStorageService>();
builder.Services.AddScoped<ITransferWorker, TelegramTransferWorker>();
builder.Services.AddScoped<TransferManager>();
await builder.Build().RunAsync();
internal sealed class WebRuntimeHost(BrowserRuntime runtime) : IRuntimeHost
{
    public bool UsesBrowserLinks => true;
    public PlatformCapabilities Capabilities => runtime.Capabilities;
    public Task<TelegramConfiguration> ConfigurationAsync() => runtime.ConfigurationAsync();
    public Task<bool> HasSavedSessionAsync(CancellationToken ct = default) => runtime.HasSavedSessionAsync(ct);
    public Task<PreparedMedia> PrepareAsync(System.Text.Json.JsonElement file, CancellationToken ct) => runtime.PrepareAsync(file, ct);
    public bool CanStream => true;
    public bool CanSaveOffline => true;
    public Task CancelOfflineSaveAsync() => runtime.CancelOfflineSaveAsync();
    public Task CancelExportAsync() => runtime.CancelExportAsync();
    public Task CancelTransferAsync(Guid operation, TransferPurpose purpose) => runtime.CancelTransferAsync(operation);
    public Task SaveOfflineTransferAsync(Track track, System.Text.Json.JsonElement file, Guid operation, CancellationToken ct) => runtime.SaveOfflineTransferAsync(track, file, operation, ct);
    public Task<string> ExportTransferAsync(System.Text.Json.JsonElement file, string name, Guid operation, CancellationToken ct) => runtime.ExportTransferAsync(file, name, operation, ct);
    public Task ValidateExportAsync(System.Text.Json.JsonElement file, CancellationToken ct) => runtime.ValidateExportAsync(file, ct);
    public Task<IReadOnlyList<OfflineCopy>> OfflineCopiesAsync(long? account, CancellationToken ct) => runtime.OfflineCopiesAsync(account, ct);
    public Task<StorageUsage> StorageUsageAsync(long account, CancellationToken ct) => runtime.StorageUsageAsync(account, ct);
    public Task CancelMediaWorkAsync() => runtime.CancelMediaWorkAsync();
    public Task<IReadOnlyList<Track>> OfflineTracksAsync(long? account, CancellationToken ct) => runtime.OfflineTracksAsync(account, ct);
    public Task SaveOfflineAsync(Track track, System.Text.Json.JsonElement file, CancellationToken ct) => runtime.SaveOfflineAsync(track, file, ct);
    public Task<PreparedMedia?> OpenOfflineAsync(Track track, CancellationToken ct) => runtime.OpenOfflineAsync(track, ct);
    public Task RemoveOfflineAsync(Track track, CancellationToken ct) => runtime.RemoveOfflineAsync(track, ct);
    public Task<PreparedMedia> StreamAsync(System.Text.Json.JsonElement file, string mime, CancellationToken ct) => runtime.StreamAsync(file, mime, ct);
    public Task<string> ExportAsync(System.Text.Json.JsonElement file, string name, CancellationToken ct) => runtime.ExportAsync(file, name, ct);
    public Task<ITagFile> OpenTagFileAsync(Track track, System.Text.Json.JsonElement? file, CancellationToken ct) => runtime.OpenTagFileAsync(track, file, ct);
    public Task<IReadOnlyMediaFile?> OpenOfflineMetadataAsync(Track track, CancellationToken ct) => runtime.OpenOfflineMetadataAsync(track, ct);
    public Task<byte[]> ReadMetadataRangeAsync(Track track, System.Text.Json.JsonElement file, long offset, int count, CancellationToken ct) => runtime.ReadMetadataRangeAsync(track, file, offset, count, ct);
    public Task<byte[]?> ReadEmbeddedArtworkAsync(Track track, System.Text.Json.JsonElement file, CancellationToken ct) => runtime.ReadEmbeddedArtworkAsync(track, file, ct);
    public Task<byte[]> ReadArtworkFileAsync(System.Text.Json.JsonElement file, CancellationToken ct) => runtime.ReadArtworkFileAsync(file, ct);
    public Task ClearSessionAsync() => runtime.ClearSessionAsync();
}
